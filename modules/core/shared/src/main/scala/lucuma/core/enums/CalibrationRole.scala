package lucuma.core.enums

import lucuma.core.util.Enumerated

enum CalibrationRole(val tag: String, val observeClass: ObserveClass, val autoGenerated: Boolean = true) derives Enumerated:
  case Twilight           extends CalibrationRole("twilight", ObserveClass.DayCal)
  case Photometric        extends CalibrationRole("photometric", ObserveClass.NightCal)
  case SpectroPhotometric extends CalibrationRole("spectrophotometric", ObserveClass.NightCal)
  case Telluric           extends CalibrationRole("telluric", ObserveClass.NightCal)
  case DaytimePinhole     extends CalibrationRole("daytime_pinhole", ObserveClass.DayCal)
  case DaytimeFlat        extends CalibrationRole("daytime_flat", ObserveClass.DayCal)
  case DaytimeArc         extends CalibrationRole("daytime_arc", ObserveClass.DayCal)
  case DaytimeCalibration extends CalibrationRole("daytime_calibration", ObserveClass.DayCal, false)
  case DaytimeMaskImage   extends CalibrationRole("daytime_mask_image", ObserveClass.DayCal)

  /**
   * Created by the ODB for one science observation, which it follows. The other `autoGenerated`
   * roles are created once for a program and configuration.
   */
  def isPerObservation: Boolean = this match
    case Telluric | DaytimePinhole | DaytimeFlat | DaytimeArc => true
    case _                                                    => false

  /**
   * Taken with no target, so it can be executed in daytime. These are the roles of `observeClass`
   * `DayCal` except `Twilight`, which is taken on sky.
   */
  def isOffSky: Boolean = this match
    case DaytimePinhole | DaytimeFlat | DaytimeArc | DaytimeCalibration | DaytimeMaskImage => true
    case _                                                                                 => false
